	var SUN = sunVector(new Date());

	function render() {
		var buf = [];
		var cosA = Math.cos(spin), sinA = Math.sin(spin);
		var cx = COLS / 2, cy = ROWS / 2;
		var twoPi = Math.PI * 2;

		for (var row = 0; row < ROWS; row++) {
			var line = "";
			for (var col = 0; col < COLS; col++) {
				var dx = (col + 0.5 - cx) / RADIUS_X;
				var dy = (row + 0.5 - cy) / RADIUS_Y;
				var d2 = dx * dx + dy * dy;
				if (d2 > 1) {
					line += " ";
					continue;
				}
				var depth = Math.sqrt(1 - d2);
				var vx = dx, vy = -dy, vz = depth; // view-space unit point on sphere

				// tilt the pole axis toward the viewer before un-spinning,
				// so the camera effectively looks slightly down at the globe
				var ty = vy * cosTilt - vz * sinTilt;
				var tz = vy * sinTilt + vz * cosTilt;
				vy = ty;
				vz = tz;

				// unspin into planet-fixed frame to sample the texture.
				// Note: uses -vx (not vx) here — with +vx the east/west
				// winding came out mirrored (confirmed visually: the
				// Americas were recognizable but flipped left-right).
				// Only the texture lookup is mirrored; vx is untouched
				// for lighting below, so shading stays geometrically correct.
				var px = -vx * cosA + vz * sinA;
				var pz = vx * sinA + vz * cosA;
				var py = vy;

				var lat = Math.asin(Math.max(-1, Math.min(1, py)));
				var lon = Math.atan2(pz, px);

				var texRow = Math.floor((0.5 - lat / Math.PI) * TEX_ROWS);
				if (texRow < 0) texRow = 0;
				if (texRow >= TEX_ROWS) texRow = TEX_ROWS - 1;
				var texCol = Math.floor(((lon / twoPi) + 0.5) * TEX_COLS) % TEX_COLS;
				if (texCol < 0) texCol += TEX_COLS;

				var ch = TEX[texRow][texCol];
				var ramp = RAMP[ch] || RAMP["."];

				var brightness = px * SUN[0] + py * SUN[1] + pz * SUN[2];
				var bucket = Math.round(((brightness + 1) / 2) * (ramp.length - 1));
				if (bucket < 0) bucket = 0;
				if (bucket >= ramp.length) bucket = ramp.length - 1;

				line += ramp[bucket];
			}
			buf.push(line);
		}
		pre.textContent = buf.join("\n");
	}

